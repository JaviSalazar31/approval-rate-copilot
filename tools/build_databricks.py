def build_functions():
    out = [notebook_header("04 · Copilot functions", [
        "Creates the five Unity Catalog SQL table functions the copilot uses for diagnosis.",
        "In the Genie agent, add them under Configure → Examples → SQL functions (trusted assets).",
        "",
        "Generated by `tools/build_databricks.py` from the SQL bodies in `/sql/copilot`. Do not edit by hand."]),
        CELL,
        f"USE CATALOG {CATALOG};\nUSE SCHEMA {SCHEMA};\n"]
    for f in FUNCTIONS:
        body = open(os.path.join(ROOT, "sql", "copilot", f"{f['name']}.sql")).read().strip().rstrip(";")
        body = body.replace("{schema}", f"{CATALOG}.{SCHEMA}.")
        body = re.sub(r"\$\{(p_[a-z_]+)\}", lambda m: m.group(1), body)
        params = []
        for n, t, d, c in f["params"]:
            p = f"  {n} {t}"
            if d is not None:
                p += f" DEFAULT {d}"
            p += f" COMMENT '{sql_str(c)}'"
            params.append(p)
        out.append(f"{CELL}CREATE OR REPLACE FUNCTION {f['name']}(\n" + ",\n".join(params) +
                   f"\n)\nRETURNS TABLE ({f['returns']})\nCOMMENT '{sql_str(f['comment'])}'\nRETURN\n{body};\n")
    out.append(f"{CELL}-- Smoke test: should return one row (CO debit incident window, local time)\n"
               "SELECT * FROM fn_drop_impact('CO', TIMESTAMP'2026-08-13 14:00:00', TIMESTAMP'2026-08-14 12:10:00', 'debit');\n")
    return "".join(out)


def main():
    targets = {
        "databricks/pipeline/approval_copilot_pipeline.sql": build_pipeline(),
        "databricks/notebooks/01_generate_data.py": build_generator_notebook(),
        "databricks/notebooks/02_build_tables_without_pipeline.sql": build_ctas(),
        "databricks/notebooks/04_copilot_functions.sql": build_functions(),
    }
    for rel, text in targets.items():
        path = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, "w").write(text)
        print(f"wrote {rel} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
