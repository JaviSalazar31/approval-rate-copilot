def read_body(rel):
    return open(os.path.join(ROOT, "sql", rel)).read().strip().rstrip(";")


def src_expr(key, streaming):
    kind, rel = SOURCES[key]
    path = f"{VOLUME_ROOT}/{rel}" + ("/" if kind == "raw" else "")
    fn = f"read_files('{path}', format => 'csv', header => true, inferColumnTypes => false)"
    return f"STREAM {fn}" if streaming else fn


def render_sources(body, streaming):
    return re.sub(r"\{src:([a-z_]+)\}", lambda m: src_expr(m.group(1), streaming), body)


def sql_str(s):
    return s.replace("'", "\\'")


def build_pipeline():
    out = [HEADER.format(title="Lakeflow pipeline, Spark Declarative Pipelines (bronze -> silver -> gold)"),
           "-- Pipeline settings: default catalog `workspace`, default schema `approval_copilot`,\n"
           "-- serverless, triggered mode. Source files land in " + VOLUME_ROOT + ".\n"
           "-- All local-time columns assume the session time zone is UTC (Databricks default).\n"]
    for name, rel, kind, comment, expectations in TABLES:
        streaming = kind == "streaming"
        body = render_sources(read_body(rel), streaming)
        obj = "STREAMING TABLE" if streaming else "MATERIALIZED VIEW"
        cons = []
        for n, cond, action in expectations:
            clause = f"  CONSTRAINT {n} EXPECT ({cond})"
            if action == "drop":
                clause += " ON VIOLATION DROP ROW"
            cons.append(clause)
        schema = "(\n" + ",\n".join(cons) + "\n)\n" if cons else ""
        out.append(f"\n-- {'-' * 84}\nCREATE OR REFRESH {obj} {name}\n{schema}"
                   f"COMMENT '{sql_str(table_comment(name, comment))}'\nAS\n{body};\n")
    return "".join(out)


CELL = "\n-- COMMAND ----------\n\n"


def notebook_header(title, lines):
    md = "\n".join(f"-- MAGIC {l}" if l else "-- MAGIC" for l in [f"# {title}", *lines])
    return f"-- Databricks notebook source\n-- MAGIC %md\n{md}\n"


def build_ctas():
    out = [notebook_header("02 · Build all tables without a pipeline (fallback)", [
        "Same SQL as the Lakeflow pipeline, written as plain `CREATE OR REPLACE TABLE` statements.",
        "Use it only if you cannot run the pipeline. Run all cells in order (about 3–5 minutes on serverless).",
        "",
        "Generated by `tools/build_databricks.py` from the SQL bodies in `/sql`. Do not edit by hand.",
        "Data: 100% synthetic. Fictional orchestrator, acquirers (A, B, C), issuers and merchants."]),
        CELL,
        f"USE CATALOG {CATALOG};\nCREATE SCHEMA IF NOT EXISTS {SCHEMA};\nUSE SCHEMA {SCHEMA};\n"
        "-- Local dates are computed from UTC instants: keep the session in UTC (serverless default).\n"
        "SET TIME ZONE 'UTC';\n"]
    for name, rel, kind, comment, expectations in TABLES:
        body = render_sources(read_body(rel), streaming=False)
        drops = [c for n, c, a in expectations if a == "drop"]
        if drops:
            body = f"SELECT * FROM (\n{body}\n) WHERE " + " AND ".join(f"({c})" for c in drops)
        out.append(f"{CELL}CREATE OR REPLACE TABLE {name}\nCOMMENT '{sql_str(table_comment(name, comment))}'\nAS\n{body};\n")
    return "".join(out)


