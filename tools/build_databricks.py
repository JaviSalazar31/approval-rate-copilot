def bundle_job(job_json: str) -> dict:
    """A job definition from this file, with the placeholders the bundle resolves at deploy time."""
    notebooks = {f.rsplit(".", 1)[0]: f for f in os.listdir(os.path.join(ROOT, "databricks", "notebooks"))}
    notebooks.update({f.rsplit(".", 1)[0]: f for f in GENERATED_NOTEBOOKS})  # written by this script, maybe not yet
    text = (job_json.replace("${PIPELINE_ID}", "${resources.pipelines.approval_copilot.id}")
                    .replace("${DBT_PROJECT_DIR}", "${workspace.file_path}/dbt")
                    .replace("${WAREHOUSE_ID}", "${var.warehouse_id}")
                    .replace("${OWNER_EMAIL}", "${workspace.current_user.userName}")
                    .replace("${PAYLOAD_DIR}/approval_copilot_agent.json",
                             "${workspace.file_path}/databricks/genie/approval_copilot_agent.json")
                    .replace("${PAYLOAD_DIR}/approval_health.lvdash.json", ""))
    text = re.sub(r"\$\{NOTEBOOK_DIR\}/([0-9a-z_]+)", lambda m: f"./databricks/notebooks/{notebooks[m.group(1)]}", text)
    return json.loads(text)


