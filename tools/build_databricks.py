def build_metric_views_notebook():
    """A Python notebook with one spark.sql call per view: a %sql cell splits statements at every semicolon, and a
    YAML comment may contain one."""
    lines = ["# 09 · Metric views",
             "Creates the Unity Catalog metric views over two gold tables: the approval, volume and decline measures,",
             "defined once as ratios of sums, so the dashboard and Genie compute them the same way. Query them with",
             "`MEASURE()`, for example `SELECT country, MEASURE(final_approval_rate) FROM approval_metrics GROUP BY ALL`.",
             "",
             "Generated by `tools/build_databricks.py` from `databricks/metric_views/*.yml`. Do not edit by hand."]
    md = "\n".join(f"# MAGIC {l}" if l else "# MAGIC" for l in lines)
    out = [f"# Databricks notebook source\n# MAGIC %md\n{md}\n"]
    for f in sorted(os.listdir(METRIC_VIEWS)):
        if not f.endswith(".yml"):
            continue
        body = open(os.path.join(METRIC_VIEWS, f), encoding="utf-8").read().splitlines()
        while body and body[0].startswith("#"):  # the file's own header comment
            body.pop(0)
        name = f[:-4]
        sql = (f"CREATE OR REPLACE VIEW {CATALOG}.{SCHEMA}.{name}\nWITH METRICS\nLANGUAGE YAML\nAS $$\n"
               + "\n".join(body).strip() + "\n$$")
        assert '"""' not in sql and "\\" not in sql, name
        out.append(f'\n# COMMAND ----------\n\nspark.sql(r"""\n{sql}\n""")  # noqa: F821\nprint("created {name}")\n')
    return "".join(out)


def module_source(rel, drop=()):
    """A module's source for a notebook cell: without `from __future__`, its main block and the given lines."""
    src = open(os.path.join(ROOT, rel), encoding="utf-8").read()
    src = src.replace("from __future__ import annotations\n", "").split('\nif __name__ == "__main__":')[0]
    for line in drop:
        assert line in src, (rel, line)
        src = src.replace(line, "")
    return src.strip() + "\n"


